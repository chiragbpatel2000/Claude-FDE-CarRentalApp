export const bookingFromRow = (r) => ({
  id: r.id, carId: r.car_id, carName: r.car_name, startDate: r.start_date, endDate: r.end_date,
  days: r.days, extras: r.extras, total: r.total, status: r.status, createdAt: r.created_at,
  customer: { name: r.customer_name, email: r.customer_email, phone: r.customer_phone },
});

// Inclusive ranges overlap when start <= other.end && end >= other.start.
export async function isCarFree(carId, start, end, db = pool) {
  const { rowCount } = await db.query(
    `SELECT 1 FROM bookings WHERE car_id = $1 AND status = 'confirmed' AND start_date <= $2 AND end_date >= $3 LIMIT 1`,
    [carId, end, start]);
  return rowCount === 0;
}
